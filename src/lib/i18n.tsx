const DICTS: Record<LangCode, Dict> = { en, te, hi, ta, kn, mr, bn, ml };

type I18nValue = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: keyof typeof en) => string;
  speechLocale: string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem("fd.lang") as LangCode | null;
    if (stored && stored in DICTS) setLangState(stored);
  }, []);

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    window.localStorage.setItem("fd.lang", l);
    document.documentElement.lang = l;
  }, []);

  const t = useCallback(
    (key: keyof typeof en) => DICTS[lang]?.[key] ?? en[key] ?? String(key),
    [lang],
  );

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      setLang,
      t,
      speechLocale: LANGUAGES.find((l) => l.code === lang)?.speech ?? "en-IN",
    }),
    [lang, setLang, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
